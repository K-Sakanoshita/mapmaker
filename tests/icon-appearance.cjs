const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const box=vm.createContext({Conf:{effect:{icon:{x:20,y:20}}}});
vm.runInContext(fs.readFileSync('lib/poislib.js','utf8'),box);
const marker=vm.runInContext('new MarkerControl()',box);
const base=marker.iconStyle(20,false,'standard'),bare=marker.iconStyle(20,false,'unframed'),subtle=marker.iconStyle(20,false,'subtle');
assert.equal(base.size,20);assert.equal(base.glyphSize,12);assert.equal(bare.glyphSize,base.glyphSize);assert.equal(bare.padding,0);assert.equal(bare.framed,false);
assert.ok(subtle.size<base.size);assert.ok(subtle.glyphSize<base.glyphSize);assert.ok(subtle.stroke<base.stroke);
assert.equal(marker.iconStyle(20,true,'standard').size,20,'existing images explicitly without frames retain their original size');
assert.equal(marker.iconStyle(20,true,'subtle').framed,false);
assert.match(marker.iconFrameSVG(subtle),/data-mapmaker-icon-frame="subtle"/);
assert.match(marker.iconFrameSVG(base),/viewBox="0 0 20 20"/);
const classes=new Set(['icon_normal']);
const image={dataset:{iconBaseSize:'20',iconNoframe:'false'},src:'icon/bench.png',style:{},classList:{toggle(name,on){on?classes.add(name):classes.delete(name);}}};
const root={style:{},firstElementChild:{style:{}},querySelector:s=>s.startsWith('img')?image:{getBoundingClientRect:()=>({width:32})}};
const positioned={getElement:()=>root,setLatLng(){assert.fail('appearance must not move the marker');}};root.mapmakerMarker=positioned;
let previews=0;box.document={querySelectorAll:()=>[root,{mapmakerMarker:{getElement:()=>({querySelector:()=>null})}}]};box.mapMaker={queueExportPreview(){previews++;}};
marker.setAppearance('unframed');assert.equal(image.style.width,'12px');assert.equal(image.style.backgroundImage,'none');assert.equal(classes.has('icon_normal'),false);
assert.equal(root.firstElementChild.style.left,'-6px');assert.equal(root.style.width,'44px');assert.equal(image.src,'icon/bench.png');
marker.setAppearance('subtle');assert.equal(image.style.width,'14px');assert.ok(image.style.backgroundImage.startsWith('url("data:image/svg+xml,'));
marker.setAppearance('standard');assert.equal(image.style.width,'20px');assert.equal(image.style.padding,'4px');assert.equal(classes.has('icon_normal'),true);
marker.setAppearance('invalid');assert.equal(box.Conf.effect.icon.preset,'standard');assert.equal(previews,3);
positioned.mapmaker_id='node/1';marker.markers.shops=[positioned];
marker.changeAppearance('shops','node/1','unframed');
assert.equal(image.dataset.iconPreset,'unframed');assert.equal(image.style.backgroundImage,'none');
assert.equal(box.Conf.effect.icon.preset,'standard','individual appearance must not change the global preset');
assert.equal(positioned.mapmaker_appearance,'unframed');
marker.setAppearance('subtle');assert.equal(positioned.mapmaker_appearance,undefined,'all-icons selection must apply to individually styled markers too');
assert.equal(image.dataset.iconPreset,'subtle');assert.equal(image.style.width,'14px');
assert.equal(previews,5);
const sizeBefore=image.style.width;
marker.changeSize('shops','node/1','0.75');assert.equal(image.dataset.iconBaseSize,'15');
assert.equal(image.dataset.iconOriginalSize,'20');assert.ok(parseFloat(image.style.width)<parseFloat(sizeBefore));
marker.changeSize('shops','node/1','1.5');assert.equal(image.dataset.iconBaseSize,'30');
const largeWidth=image.style.width;assert.ok(parseFloat(largeWidth)>parseFloat(sizeBefore));
marker.applyAppearance(positioned);assert.equal(image.style.width,largeWidth,'reapplying appearance must not multiply the size again');
marker.changeSize('shops','node/1','1');assert.equal(image.style.width,sizeBefore);
for(const value of ['invalid',0,100,null])marker.changeSize('shops','node/1',value);
assert.equal(positioned.mapmaker_icon_scale,1);assert.equal(box.Conf.effect.icon.x,20);
assert.equal(root.style.width,String(parseFloat(sizeBefore)+32)+'px','label width remains unchanged');
assert.equal(previews,8);
console.log('PASS shared icon geometry, three presets, explicit frameless assets, live updates, anchor alignment, position preservation, image preservation and QR exclusion');
